#!/usr/bin/env python3
"""Write COVERAGE.md: what the corpus holds, per system and core, against the registry.

    python3 -I tools/coverage.py [REGISTRY_DATA_DIR]

Reads every provenance.json under corpus/<system>/ and the registry's systems.json and
cores.json (default: ../one-saves/crates/one-saves-registry/data). For each system it lists
every core the registry gives it, how many entries each has and how they were made, and the
directories here that are not registry cores (`core@app`, `_producer`).
"""

import collections
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
REG = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    ROOT, "..", "one-saves", "crates", "one-saves-registry", "data")
SKIP = {"tools", "scripts", "work", ".cache"}
SHORT = {"played": "P", "downloaded": "D", "device-backup": "B", "handoff": "H"}


def main():
    systems = json.load(open(os.path.join(REG, "systems.json")))
    cores = json.load(open(os.path.join(REG, "cores.json")))
    by_system = collections.defaultdict(list)
    for c in cores:
        for s in c["systems"]:
            by_system[s].append(c)

    # counts[system][core dir][method] = n
    counts = collections.defaultdict(lambda: collections.defaultdict(collections.Counter))
    games = collections.defaultdict(set)
    for system in sorted(os.listdir(ROOT)):
        sdir = os.path.join(ROOT, system)
        if system in SKIP or system.startswith(".") or not os.path.isdir(sdir):
            continue
        for base, _, files in os.walk(sdir):
            if "provenance.json" not in files:
                continue
            rel = os.path.relpath(base, sdir).split(os.sep)
            try:
                method = json.load(open(os.path.join(base, "provenance.json"))).get("method", "?")
            except ValueError:
                method = "unreadable"
            counts[system][rel[0]][method] += 1
            if len(rel) > 1:
                # "<release> [GameFAQs 123]" is one more save of <release>
                games[system].add(re.sub(r" \[GameFAQs \d+\]$", "", rel[1]))

    # Systems the corpus holds that the registry has not added yet (e.g. pico-8) go last.
    known = {s["slug"] for s in systems}
    extra = sorted(s for s in counts if s not in known)
    systems = systems + [{"slug": s} for s in extra]

    out = ["# Coverage", "",
           "Generated by `tools/coverage.py` from every `provenance.json` and the registry. "
           "Methods: P played, H handoff, D downloaded, B device backup. A core with no entries "
           "is listed with a dash.", ""]
    total = sum(sum(m.values()) for s in counts.values() for m in s.values())
    covered = sum(1 for s in by_system for c in by_system[s] if counts[s].get(c["slug"]))
    pairs = sum(len(v) for v in by_system.values())
    out += [f"**{total} entries.** {covered} of {pairs} registry (system, core) pairs have at "
            f"least one entry.", ""]
    out += ["| System | Games | Entries | Cores covered | Registry cores without entries |",
            "| --- | ---: | ---: | ---: | --- |"]
    for s in systems:
        slug = s["slug"]
        regs = by_system.get(slug, [])
        have = [c for c in regs if counts[slug].get(c["slug"])]
        missing = [c["slug"] for c in regs if not counts[slug].get(c["slug"])]
        n = sum(sum(m.values()) for m in counts[slug].values())
        note = "not a registry system yet" if slug in extra else ", ".join(missing)
        out.append(f"| {slug} | {len(games[slug])} | {n} | {len(have)}/{len(regs)} | {note} |")
    out.append("")

    for s in systems:
        slug = s["slug"]
        if not counts[slug] and not by_system.get(slug):
            continue
        out += [f"## {slug}", "", "| Core | Kind | Entries |", "| --- | --- | --- |"]
        listed = set()
        for c in sorted(by_system.get(slug, []), key=lambda c: c["slug"]):
            listed.add(c["slug"])
            m = counts[slug].get(c["slug"])
            cell = ", ".join(f"{n} {SHORT.get(k, k)}" for k, n in sorted(m.items())) if m else "-"
            out.append(f"| {c['slug']} | {c['kind']} | {cell} |")
        for d in sorted(set(counts[slug]) - listed):
            m = counts[slug][d]
            cell = ", ".join(f"{n} {SHORT.get(k, k)}" for k, n in sorted(m.items()))
            out.append(f"| {d} | not a registry core | {cell} |")
        out.append("")

    with open(os.path.join(ROOT, "COVERAGE.md"), "w") as f:
        f.write("\n".join(out))
    print(f"{total} entries, {covered}/{pairs} registry pairs covered -> COVERAGE.md")


if __name__ == "__main__":
    main()
