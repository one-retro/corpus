#!/usr/bin/env python3
"""Write GAMEFAQS.md: what the GameFAQs saves are and which cores load them.

    python3 -I tools/gamefaqs/summary.py

Reads every `<system>/<producer>/<release> [GameFAQs <id>]/provenance.json` (tools/GAMEFAQS.md
describes the entries) and tabulates, per system, the entries by producer and, per core, the
verification results: loads, rejected, core-error, not-run. Details and findings are in each
system's NOTES.md, section "GameFAQs saves".
"""
import collections
import glob
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
RESULTS = ("loads", "rejected", "core-error", "not-run")


def main():
    os.chdir(ROOT)
    entries = collections.defaultdict(list)
    for p in sorted(glob.glob("*/*/* [[]GameFAQs *[]]/provenance.json")):
        system, producer = p.split(os.sep)[:2]
        entries[system].append((producer, json.load(open(p))))
    total = sum(len(v) for v in entries.values())
    tally = collections.Counter()
    for v in entries.values():
        for _, j in v:
            for r in ((j.get("verified") or {}).get("cores") or {}).values():
                tally[r.get("result")] += 1

    out = ["# GameFAQs saves", "",
           "Generated by `tools/gamefaqs/summary.py`. Every save GameFAQs had (2026-11-05) for a game "
           "in this corpus, in a format of the system's own hardware or save devices, filed as it was "
           "served and loaded into every runnable core after conversion (`tools/GAMEFAQS.md`). Each "
           "system's NOTES.md, section \"GameFAQs saves\", has the formats, findings and failures.", "",
           f"**{total} entries.** Core runs: " + ", ".join(f"{tally[r]} {r}" for r in RESULTS) + ".", "",
           "`loads`: the game showed what the save holds. `rejected`: it saw no save, or a blank or "
           "corrupt one. `core-error`: the core failed or hung. `not-run`: no image of that release "
           "here, the core cannot run here, or nothing to convert.", "",
           "| System | Entries | By producer |", "| --- | ---: | --- |"]
    for system in sorted(entries):
        by = collections.Counter(p for p, _ in entries[system])
        out.append(f"| {system} | {len(entries[system])} | "
                   + ", ".join(f"`{p}` {n}" for p, n in by.most_common()) + " |")
    for system in sorted(entries):
        per = collections.defaultdict(collections.Counter)
        for _, j in entries[system]:
            for core, r in ((j.get("verified") or {}).get("cores") or {}).items():
                per[core][r.get("result")] += 1
        out += ["", f"## {system}", "", "| Core | " + " | ".join(RESULTS) + " |",
                "| --- | " + " | ".join("---:" for _ in RESULTS) + " |"]
        for core in sorted(per, key=lambda c: (-per[c]["loads"], c)):
            out.append(f"| {core} | " + " | ".join(str(per[core][r]) for r in RESULTS) + " |")
    open("GAMEFAQS.md", "w").write("\n".join(out) + "\n")
    print(f"{total} entries -> GAMEFAQS.md")


if __name__ == "__main__":
    main()
